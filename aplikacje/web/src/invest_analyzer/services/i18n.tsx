export function translate(language: UiLanguage, key: TranslationKey | string, params: TranslationParams = {}): string {
  const dictionary = language === 'en' ? enTranslations : plTranslations;
  const template = (dictionary as Record<string, string | undefined>)[key] || (plTranslations as Record<string, string | undefined>)[key] || key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? ''));
}

export function translateEngineMessage(language: UiLanguage, codeOrMessage: string | null | undefined): string {
  const raw = String(codeOrMessage || '').trim();
  if (!raw) return '';
  const code = raw.split(':')[0]?.trim();
  const codeKey = `silnik.${code}`;
  const translated = translate(language, codeKey);
  if (translated !== codeKey) return translated;
  return raw;
}

export interface I18nApi {
  language: UiLanguage;
  t: (key: TranslationKey | string, params?: TranslationParams) => string;
  formatMoney: (value: string | number | null | undefined, currency?: string) => string;
  formatNumber: (value: string | number | null | undefined) => string;
  formatDate: (value: string | Date | null | undefined) => string;
}

const I18nContext = createContext<I18nApi | null>(null);

export function I18nProvider({ language, children }: { language: UiLanguage; children: React.ReactNode }) {
  const api = useMemo<I18nApi>(() => {
    const locale = language === 'en' ? 'en-US' : 'pl-PL';
    return {
      language,
      t: (key, params) => translate(language, key, params),
      formatMoney: (value, currency = 'PLN') => {
        const numeric = Number(value ?? 0);
        return new Intl.NumberFormat(locale, { style: 'currency', currency }).format(Number.isFinite(numeric) ? numeric : 0);
      },
      formatNumber: (value) => {
        const numeric = Number(value ?? 0);
        return new Intl.NumberFormat(locale).format(Number.isFinite(numeric) ? numeric : 0);
      },
      formatDate: (value) => {
        if (!value) return '';
        const date = value instanceof Date ? value : new Date(value);
        if (Number.isNaN(date.getTime())) return String(value);
        return new Intl.DateTimeFormat(locale).format(date);
      },
    };
  }, [language]);

  return <I18nContext.Provider value={api}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nApi {
  const context = useContext(I18nContext);
  if (!context) {
    return {
      language: 'pl',
      t: (key, params) => translate('pl', key, params),
      formatMoney: (value, currency = 'PLN') => new Intl.NumberFormat('pl-PL', { style: 'currency', currency }).format(Number(value ?? 0) || 0),
      formatNumber: (value) => new Intl.NumberFormat('pl-PL').format(Number(value ?? 0) || 0),
      formatDate: (value) => {
        if (!value) return '';
        const date = value instanceof Date ? value : new Date(value);
        return Number.isNaN(date.getTime()) ? String(value) : new Intl.DateTimeFormat('pl-PL').format(date);
      },
    };
  }
  return context;
}
